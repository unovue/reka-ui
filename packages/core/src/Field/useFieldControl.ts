import type { ComputedRef, MaybeRefOrGetter } from 'vue'
import type { PartSurface } from '@/shared'
import { toValue, watch } from 'vue'
import { createPartSurface, getterRef } from '@/shared/partSurface'
import { useFieldBinding } from './useFieldBinding'

/** The state of a field's control; each key that is set renders as a `data-*` attribute. */
export type FieldControlState = {
  disabled: boolean
  /** `null` until the field has been validated. */
  valid: boolean | null
  invalid: boolean
  dirty: boolean
  touched: boolean
  filled: boolean
  focused: boolean
}

export interface UseFieldControlProps<T = unknown> {
  /**
   * The control's current value: what the field's `validate` receives and
   * what `FormRoot` collects under the field's `name`. A change the composable
   * observes here without an `input()` call (the parent set the model) only
   * updates the field's `filled` state.
   */
  value: MaybeRefOrGetter<T>
  /** The element that takes focus when the field's label is clicked, or when the field is the first invalid one on submit. */
  element: MaybeRefOrGetter<HTMLElement | null | undefined>
  /** The control's own `id`. The id generated by the field is used when it is unset. */
  id?: MaybeRefOrGetter<string | undefined>
  /** The control's own `name`, used when the field has none. */
  name?: MaybeRefOrGetter<string | undefined>
  /** Disables the control. A disabled field disables it too. */
  disabled?: MaybeRefOrGetter<boolean | undefined>
  /** Makes the control required. A required field makes it required too. */
  required?: MaybeRefOrGetter<boolean | undefined>
  /**
   * A native `input`, `textarea` or `select` whose constraint validation
   * (`required`, `pattern`, `min`, …) decides the field's validity, and which
   * receives the field's custom errors. Without one, the only built-in
   * constraint is `required`, checked with `isFilled`.
   */
  validityElement?: MaybeRefOrGetter<HTMLInputElement | HTMLTextAreaElement | HTMLSelectElement | null | undefined>
  /**
   * Whether a value counts as filled. Decides the field's `filled` state and,
   * without a `validityElement`, whether a required control is missing its value.
   * @defaultValue anything but `null`, `undefined`, `''` and an empty array
   */
  isFilled?: (value: T) => boolean
}

export interface UseFieldControlReturn<T = unknown> {
  /** The control's own `id`, or the one generated by the field. `undefined` outside a field without an own `id`. */
  id: ComputedRef<string | undefined>
  /** The field's `name`, or the control's own when the field has none. */
  name: ComputedRef<string | undefined>
  /** Whether the control or its field is disabled. */
  disabled: ComputedRef<boolean>
  /** Whether the control or its field is required. */
  required: ComputedRef<boolean>
  /**
   * Reports a change made by the user: the field becomes dirty when the value
   * differs from its initial one, validates when its mode asks for it, and
   * drops a server error. Pass the new value when `value` does not hold it
   * yet, as with a model the parent updates on its next render.
   */
  input: (value?: T) => void
  /**
   * What to render on the control's element: its `id`, the `aria-labelledby`,
   * `aria-describedby` and `aria-invalid` wiring, the focus and blur handlers,
   * and the field's state as `data-*` attributes.
   */
  control: PartSurface<FieldControlState>
}

const STANDALONE_STATE: FieldControlState = {
  disabled: false,
  valid: null,
  invalid: false,
  dirty: false,
  touched: false,
  filled: false,
  focused: false,
}

/**
 * Makes your own control the control of the enclosing `FieldRoot`, the way the
 * Reka UI form controls are: it takes the field's `id`, `name`, `disabled` and
 * `required`, is labelled and described by the field's parts, reports focus,
 * touched, dirty and filled state, and gives its value to validation and to
 * `FormRoot`.
 *
 * Outside a `FieldRoot` it returns the control's own `id`, `name`, `disabled`
 * and `required` and no field wiring, so one component works in both places.
 * A control rendered inside another control of the same field leaves the
 * field to the outer one.
 *
 * @experimental Signatures may change in 3.x minors.
 * @lifecycle setup — registers on mount and watches `value`; call it inside `setup()`.
 */
export function useFieldControl<T = unknown>(props: UseFieldControlProps<T>): UseFieldControlReturn<T> {
  const value = () => toValue(props.value)
  const ownDisabled = () => toValue(props.disabled)
  const ownRequired = () => toValue(props.required)

  const binding = useFieldBinding({
    id: () => toValue(props.id),
    element: () => toValue(props.element),
    getValue: value,
    validityElement: props.validityElement === undefined ? undefined : () => toValue(props.validityElement),
    required: () => Boolean(ownRequired()),
    isFilled: props.isFilled as ((value: unknown) => boolean) | undefined,
  })

  const disabled = () => binding ? binding.disabled(ownDisabled()) : Boolean(ownDisabled())

  // A change that arrives through `value` alone is the parent's: only `filled` follows it.
  if (binding)
    watch(value, next => binding.sync(next))

  return {
    id: getterRef(() => binding ? binding.id() : toValue(props.id)),
    name: getterRef(() => binding ? binding.name(toValue(props.name)) : toValue(props.name)),
    disabled: getterRef(disabled),
    required: getterRef(() => binding ? binding.required(ownRequired()) : Boolean(ownRequired())),
    input: (...args) => binding?.input(args.length ? args[0] : value()),
    control: createPartSurface<FieldControlState>(
      () => {
        if (!binding)
          return { id: toValue(props.id) }
        const { context } = binding
        return {
          'id': binding.id(),
          'aria-labelledby': context.labelId.value,
          'aria-describedby': context.describedBy.value,
          'aria-invalid': (context.invalid.value && !disabled()) || undefined,
          'onFocus': binding.onFocus,
          'onBlur': binding.onBlur,
        }
      },
      () => {
        if (!binding)
          return ownDisabled() ? { ...STANDALONE_STATE, disabled: true } : STANDALONE_STATE
        const { context } = binding
        return {
          disabled: disabled(),
          valid: context.valid.value,
          invalid: context.invalid.value,
          dirty: context.dirty.value,
          touched: context.touched.value,
          filled: context.filled.value,
          focused: context.focused.value,
        }
      },
    ),
  }
}
